// 只碰这两个属性,不动 id/value/dataset,故 hookbtn/select/option 的行为与 paintThm 均不受影响。
function applyI18n(): void {
  document.documentElement.lang = lang;
  document.querySelectorAll<HTMLElement>('[data-i18n]').forEach(el => {
    const k = el.getAttribute('data-i18n'); if (k) el.textContent = T(k);
  });
  document.querySelectorAll<HTMLElement>('[data-i18n-ph]').forEach(el => {
    const k = el.getAttribute('data-i18n-ph'); if (k) (el as HTMLInputElement).placeholder = T(k);
  });
}
