const T = (k: string, ...args: (string | number)[]): string => {
  let s = lang === 'zh' ? k : (I18N[lang][k] || k);
  for (let i = 0; i < args.length; i++) s = s.split('%' + (i + 1)).join(String(args[i]));
  return s;
};
