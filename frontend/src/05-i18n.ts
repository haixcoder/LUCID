function detectLang(): Lang {
  const s = localStorage.getItem('wfo-lang');
  if (s && LANGS.some(l => l.id === s)) return s as Lang;
  const nav = String(navigator.language || 'zh').slice(0, 2).toLowerCase() as Lang;
  return LANGS.some(l => l.id === nav) ? nav : 'zh';   // 首次访问跟随浏览器语言,兜底中文(源语言)
}
